begin;
do $$ declare c uuid; h uuid; a uuid; p uuid; q uuid; mid uuid; official uuid; j jsonb; original jsonb; standings jsonb; scorers jsonb; rejected boolean; version timestamptz;
begin
 insert into public.categories(name) values('__032') returning id into c;
 insert into public.teams(category_id,name) values(c,'H') returning id into h;
 insert into public.teams(category_id,name) values(c,'A') returning id into a;
 insert into public.players(team_id,full_name) values(h,'Player H') returning id into p;
 insert into public.players(team_id,full_name) values(a,'Player A') returning id into q;
 insert into public.matches(category_id,matchday_id,home_team_id,away_team_id,scheduled_date)
 select c,id,h,a,'2026-10-15' from public.matchdays where number=1 returning id into official;
 select coalesce(jsonb_agg(to_jsonb(s)),'[]') into standings from public.get_standings(c,false) s;
 select coalesce(jsonb_agg(to_jsonb(s)),'[]') into scorers from public.get_top_scorers(c) s;
 set local role anon;
 j:=public.create_friendly(c,h,a,'2028-01-02','18:00',900,false,gen_random_uuid());mid:=(j->'match'->>'id')::uuid;
 assert not (j->'match'->>'friendly_penalties')::boolean;
 perform public.set_match_duration(mid,1200,(j->'match'->>'updated_at')::timestamptz);
 perform public.set_match_player(mid,p,7,true,(select updated_at from public.matches where id=mid));
 perform public.set_match_player(mid,q,9,true,(select updated_at from public.matches where id=mid));
 perform public.save_match_precheck(mid,true,true,true,true,(select updated_at from public.matches where id=mid));
 perform public.control_match(mid,'START',(select updated_at from public.matches where id=mid));
 perform public.record_match_event(mid,h,'GOAL',p,gen_random_uuid());
 perform public.record_match_event(mid,a,'YELLOW_CARD',q,gen_random_uuid());
 perform public.control_match(mid,'BREAK',(select updated_at from public.matches where id=mid));
 perform public.control_match(mid,'SECOND_HALF',(select updated_at from public.matches where id=mid));
 perform public.control_match(mid,'FINISH',(select updated_at from public.matches where id=mid));
 original:=public.get_match_control(mid);version:=(original->'match'->>'updated_at')::timestamptz;
 perform set_config('request.jwt.claims','{}',true);
 j:=public.reopen_match(mid,version);
 assert j->'match'->>'status'='PAUSADO';
 assert j->'score'=original->'score' and j->'events'=original->'events' and j->'lineup'=original->'lineup';
 assert j->'match'->>'period_duration_seconds'='1200';
 assert j->'match'->>'phase_elapsed_seconds'=original->'match'->>'phase_elapsed_seconds';
 rejected:=false;
 begin perform public.reopen_match(mid,version); exception when raise_exception then rejected:=true; end;
 assert rejected,'Repeated reopen must not duplicate changes';
 rejected:=false;
 begin perform public.set_match_duration(mid,900,(j->'match'->>'updated_at')::timestamptz); exception when raise_exception then rejected:=true; end;
 assert rejected,'Reopened duration stays fixed';
 perform public.control_match(mid,'RESUME',(select updated_at from public.matches where id=mid));
 j:=public.control_match(mid,'FINISH',(select updated_at from public.matches where id=mid));
 assert j->'score'=original->'score' and j->'events'=original->'events';
 assert exists(select 1 from jsonb_array_elements(public.get_tournament()->'matches') t where t->'match'->>'id'=mid::text),'Calendar/live snapshot includes friendly';
 assert (select scheduled_date='2026-10-15' from public.matches where id=official);
 assert (select scheduled_date='2028-01-02' from public.matches where id=mid);
 -- No advance configuration is required: start penalties explicitly in control.
 j:=public.create_friendly(c,h,a,null,null,900,false,gen_random_uuid());mid:=(j->'match'->>'id')::uuid;
 reset role;
 update public.matches set status='PAUSADO',paused_from_status='SEGUNDO_TIEMPO',phase_elapsed_seconds=900 where id=mid;
 set local role anon;
 j:=public.get_match_control(mid);
 assert j->'shootout'='null'::jsonb,'Reading control never starts a shootout';
 j:=public.open_penalty_shootout(mid,gen_random_uuid(),(j->'match'->>'updated_at')::timestamptz);
 assert (j->'match'->>'friendly_penalties')::boolean;
 j:=public.manage_penalty_shootout(mid,'SET_THREE',null,null,null,gen_random_uuid(),0);
 for i in 0..5 loop
   j:=public.manage_penalty_shootout(mid,'RECORD',case when i%2=0 then h else a end,null,i<>5,gen_random_uuid(),i+1);
 end loop;
 assert j->'match'->>'status'='FINALIZADO';
 assert j->'shootout'->'score'='{"home":3,"away":2}'::jsonb;
 original:=j;
 j:=public.reopen_match(mid,(j->'match'->>'updated_at')::timestamptz);
 assert j->'shootout'->'attempts'=original->'shootout'->'attempts';
 j:=public.manage_penalty_shootout(mid,'FINISH',null,null,null,gen_random_uuid(),(j->'shootout'->>'revision')::int);
 assert j->'shootout'->'score'='{"home":3,"away":2}'::jsonb;
 assert (select coalesce(jsonb_agg(to_jsonb(s)),'[]') from public.get_standings(c,false) s)=standings;
 assert (select coalesce(jsonb_agg(to_jsonb(s)),'[]') from public.get_top_scorers(c) s)=scorers;
 -- Official matches use the same anonymous administrative reopening.
 reset role;
 perform public.set_match_player(official,p,7,true,(select updated_at from public.matches where id=official));
 perform public.set_match_player(official,q,9,true,(select updated_at from public.matches where id=official));
 perform public.save_match_precheck(official,true,true,true,true,(select updated_at from public.matches where id=official));
 perform public.control_match(official,'START',(select updated_at from public.matches where id=official));
 perform public.control_match(official,'BREAK',(select updated_at from public.matches where id=official));
 perform public.control_match(official,'SECOND_HALF',(select updated_at from public.matches where id=official));
 update public.matches set phase_started_at=clock_timestamp()-interval '90 seconds' where id=official;
 perform public.control_match(official,'FINISH',(select updated_at from public.matches where id=official));
 set local role anon;
 j:=public.reopen_match(official,(select updated_at from public.matches where id=official));
 assert j->'match'->>'status'='PAUSADO';
 assert j->'match'->>'phase_elapsed_seconds'='90';
end $$;
rollback;
