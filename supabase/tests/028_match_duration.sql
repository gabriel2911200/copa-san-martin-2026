begin;
do $$ declare c uuid; h uuid; a uuid; t3 uuid; t4 uuid; mid uuid; sf2 uuid; p uuid; q uuid; j jsonb; rejected boolean; phase text; limit_seconds integer;
begin
  assert not exists(select 1 from public.matches where period_duration_seconds<>900),'Existing fixtures stay at 15 minutes';
  insert into public.categories(name) values('__028_duration') returning id into c;
  insert into public.teams(category_id,name) values(c,'A') returning id into h;
  insert into public.teams(category_id,name) values(c,'B') returning id into a;
  insert into public.teams(category_id,name) values(c,'C') returning id into t3;
  insert into public.teams(category_id,name) values(c,'D') returning id into t4;
  insert into public.players(team_id,full_name) values(h,'Home player') returning id into p;
  insert into public.players(team_id,full_name) values(a,'Away player') returning id into q;
  foreach limit_seconds in array array[900,1200] loop
    insert into public.matches(category_id,matchday_id,home_team_id,away_team_id)
      values(c,(select id from public.matchdays where number=case when limit_seconds=900 then 1 else 2 end),h,a) returning id into mid;
    assert (select period_duration_seconds=900 from public.matches where id=mid);
    set local role anon;
    rejected:=false;
    begin perform public.set_match_duration(mid,1000,(select updated_at from public.matches where id=mid)); exception when raise_exception then rejected:=true; end;
    assert rejected;
    rejected:=false;
    begin perform public.set_match_duration(mid,1200,'2000-01-01'); exception when raise_exception then rejected:=true; end;
    assert rejected,'Stale duration update rejected';
    j:=public.set_match_duration(mid,limit_seconds,(select updated_at from public.matches where id=mid));
    assert (j->'match'->>'period_duration_seconds')::int=limit_seconds;
    perform public.set_match_player(mid,p,7,true,(select updated_at from public.matches where id=mid));
    perform public.set_match_player(mid,q,8,true,(select updated_at from public.matches where id=mid));
    perform public.save_match_precheck(mid,true,true,true,true,(select updated_at from public.matches where id=mid));
    perform public.control_match(mid,'START',(select updated_at from public.matches where id=mid));
    rejected:=false;
    begin perform public.set_match_duration(mid,case when limit_seconds=900 then 1200 else 900 end,(select updated_at from public.matches where id=mid)); exception when raise_exception then rejected:=true; end;
    assert rejected,'Started duration is immutable';
    reset role;
    rejected:=false;
    begin update public.matches set period_duration_seconds=case when limit_seconds=900 then 1200 else 900 end where id=mid; exception when raise_exception then rejected:=true; end;
    assert rejected,'Trigger also protects direct writes';
    update public.matches set phase_started_at=clock_timestamp()-make_interval(secs=>limit_seconds-10) where id=mid;
    set local role anon;
    j:=public.record_match_event(mid,h,'GOAL',p,gen_random_uuid());
    assert (j->'event'->>'clock_seconds')::int>=limit_seconds-10;
    j:=public.record_own_goal(mid,a,gen_random_uuid());
    assert (j->'event'->>'clock_seconds')::int>=limit_seconds-10;
    perform public.control_match(mid,'BREAK',(select updated_at from public.matches where id=mid));
    reset role;
    update public.matches set phase_started_at=clock_timestamp()-interval '400 seconds' where id=mid;
    set local role anon;
    j:=public.control_match(mid,'PAUSE',(select updated_at from public.matches where id=mid));
    assert (j->'match'->>'phase_elapsed_seconds')::int=300,'Break remains five minutes';
    perform public.control_match(mid,'RESUME',(select updated_at from public.matches where id=mid));
    j:=public.control_match(mid,'SECOND_HALF',(select updated_at from public.matches where id=mid));
    assert (j->'match'->>'phase_elapsed_seconds')::int=0;
    reset role;
    update public.matches set phase_started_at=clock_timestamp()-make_interval(secs=>limit_seconds+10) where id=mid;
    set local role anon;
    j:=public.control_match(mid,'FINISH',(select updated_at from public.matches where id=mid));
    assert (j->'match'->>'phase_elapsed_seconds')::int=limit_seconds;
    rejected:=false;
    begin perform public.set_match_duration(mid,1200,(select updated_at from public.matches where id=mid)); exception when raise_exception then rejected:=true; end;
    assert rejected;
    reset role;
  end loop;
  -- Separate category: generate all three playoff stages through the real workflow.
  insert into public.categories(name) values('__028_playoffs') returning id into c;
  insert into public.teams(category_id,name) values(c,'A') returning id into h;
  insert into public.teams(category_id,name) values(c,'B') returning id into a;
  insert into public.teams(category_id,name) values(c,'C') returning id into t3;
  insert into public.teams(category_id,name) values(c,'D') returning id into t4;
  perform public.close_regular(c);
  perform public.create_semifinals(c,h,a,t3,t4);
  select id into sf2 from public.matches where category_id=c and home_team_id=t3;
  foreach phase in array array['SEMIFINAL','FINAL','THIRD_PLACE'] loop
    select id into mid from public.matches where category_id=c and stage=phase and id<>sf2;
    set local role anon;
    perform public.set_match_duration(mid,1200,(select updated_at from public.matches where id=mid));
    perform public.save_match_precheck(mid,true,true,true,true,(select updated_at from public.matches where id=mid));
    perform public.control_match(mid,'START',(select updated_at from public.matches where id=mid));
    perform public.control_match(mid,'BREAK',(select updated_at from public.matches where id=mid));
    perform public.control_match(mid,'SECOND_HALF',(select updated_at from public.matches where id=mid));
    perform public.control_match(mid,'PAUSE',(select updated_at from public.matches where id=mid));
    reset role;
    update public.matches set phase_elapsed_seconds=900 where id=mid;
    set local role anon;
    rejected:=false;
    begin perform public.open_penalty_shootout(mid,gen_random_uuid(),(select updated_at from public.matches where id=mid)); exception when raise_exception then rejected:=true; end;
    assert rejected,'20-minute playoffs cannot open penalties at 15';
    reset role;
    update public.matches set phase_elapsed_seconds=1200 where id=mid;
    select home_team_id,away_team_id into h,a from public.matches where id=mid;
    set local role anon;
    j:=public.open_penalty_shootout(mid,gen_random_uuid(),(select updated_at from public.matches where id=mid));
    assert j->'shootout' is not null;
    for n in 0..2 loop
      perform public.manage_penalty_shootout(mid,'RECORD',h,null,true,gen_random_uuid(),n*2);
      j:=public.manage_penalty_shootout(mid,'RECORD',a,null,false,gen_random_uuid(),n*2+1);
    end loop;
    assert j->'match'->>'status'='FINALIZADO';
    assert (j->'match'->>'phase_elapsed_seconds')::int=1200;
    reset role;
    if phase='SEMIFINAL' then perform public.record_walkover(sf2,t4,gen_random_uuid(),(select updated_at from public.matches where id=sf2)); end if;
  end loop;
  assert (select count(*)=2 from public.matches where category_id=c and stage in('FINAL','THIRD_PLACE'));
end $$;
rollback;
