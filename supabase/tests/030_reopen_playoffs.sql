begin;
do $$ declare c uuid; h uuid; a uuid; b uuid; d uuid; p uuid; q uuid; mid uuid; sf uuid; j jsonb; rejected boolean; original jsonb;
begin
 insert into public.categories(name) values('__030_reopen_final') returning id into c;
 insert into public.teams(category_id,name) values(c,'A') returning id into h;
 insert into public.teams(category_id,name) values(c,'B') returning id into a;
 insert into public.teams(category_id,name) values(c,'C') returning id into b;
 insert into public.teams(category_id,name) values(c,'D') returning id into d;
 perform public.close_regular(c);
 perform public.create_semifinals(c,h,a,b,d);
 for sf in select id from public.matches where category_id=c and stage='SEMIFINAL' loop
   perform public.record_walkover(sf,(select away_team_id from public.matches where id=sf),gen_random_uuid(),(select updated_at from public.matches where id=sf));
 end loop;
 select id into mid from public.matches where category_id=c and stage='FINAL';
 assert mid is not null;
 insert into public.players(team_id,full_name) select home_team_id,'Home player' from public.matches where id=mid returning id into p;
 insert into public.players(team_id,full_name) select away_team_id,'Away player' from public.matches where id=mid returning id into q;
 perform public.set_match_player(mid,p,8,true,(select updated_at from public.matches where id=mid));
 perform public.set_match_player(mid,q,8,true,(select updated_at from public.matches where id=mid));
 perform public.save_match_precheck(mid,true,true,true,true,(select updated_at from public.matches where id=mid));
 perform public.control_match(mid,'START',(select updated_at from public.matches where id=mid));
 perform public.record_own_goal(mid,h,gen_random_uuid());
 perform public.control_match(mid,'BREAK',(select updated_at from public.matches where id=mid));
 perform public.control_match(mid,'SECOND_HALF',(select updated_at from public.matches where id=mid));
 update public.matches set phase_started_at=clock_timestamp()-interval '90 seconds' where id=mid;
 perform public.control_match(mid,'FINISH',(select updated_at from public.matches where id=mid));
 original:=public.get_match_control(mid);
 perform set_config('request.jwt.claims',jsonb_build_object('role','authenticated','sub',gen_random_uuid(),'app_metadata',jsonb_build_object('role','viewer'))::text,true);
 rejected:=false;
 begin perform public.reopen_match(mid,(select updated_at from public.matches where id=mid)); exception when insufficient_privilege then rejected:=true; end;
 assert rejected,'Authenticated non-admin cannot reopen';
 perform set_config('request.jwt.claims',jsonb_build_object('role','authenticated','sub',gen_random_uuid(),'app_metadata',jsonb_build_object('role','admin'))::text,true);
 set local role authenticated;
 j:=public.reopen_match(mid,(original->'match'->>'updated_at')::timestamptz);
 assert j->'score'=original->'score' and j->'events'=original->'events';
 assert j->'match'->>'status'='PAUSADO';
 assert (j->'match'->>'phase_elapsed_seconds')::int>=90;
 reset role;
 set local role anon;
 j:=public.control_match(mid,'RESUME',(select updated_at from public.matches where id=mid));
 perform public.record_own_goal(mid,h,gen_random_uuid());
 j:=public.control_match(mid,'FINISH',(select updated_at from public.matches where id=mid));
 assert j->'score'='{"home":2,"away":0}'::jsonb;
 reset role;
 assert (select count(*)=1 from private.match_reopen_audit where match_id=mid);
 -- No automatic rewrites of previously closed standings or W.O. results.
 rejected:=false;
 begin perform public.reopen_match(sf,(select updated_at from public.matches where id=sf)); exception when raise_exception then rejected:=true; end;
 assert rejected;
end $$;
rollback;
