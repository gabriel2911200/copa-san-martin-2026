begin;
create function public.__reset_test_snapshot() returns jsonb language plpgsql as $$
declare result jsonb:='{}'; t text; value jsonb;
begin
  foreach t in array array['categories','matchdays','teams','players','matches','match_events','match_players','match_prechecks','match_foul_counters','player_initial_goals','penalty_shootouts','penalty_shootout_attempts','penalty_shootout_operations'] loop
    execute format('select coalesce(jsonb_agg(to_jsonb(x) order by to_jsonb(x)::text),''[]''::jsonb) from public.%I x',t) into value;
    result:=result||jsonb_build_object(t,value);
  end loop;
  return result;
end $$;
create function public.__reset_fail() returns trigger language plpgsql as $$ begin raise exception 'Injected reset failure'; end $$;
do $$ declare c uuid; h uuid; a uuid; t3 uuid; t4 uuid; p uuid; q uuid; mid uuid; generation uuid; rid uuid:=gen_random_uuid(); before_j jsonb; j jsonb; rejected boolean; t text; n integer;
begin
  assert has_function_privilege('anon','public.reset_tournament(text,uuid,uuid)','EXECUTE');
  assert has_function_privilege('anon','public.prepare_tournament_reset()','EXECUTE');
  assert not has_table_privilege('anon','private.tournament_reset_state','UPDATE');
  assert not has_table_privilege('authenticated','public.matches','DELETE');
  insert into public.categories(name) values('__029_reset') returning id into c;
  insert into public.teams(category_id,name) values(c,'A') returning id into h;
  insert into public.teams(category_id,name) values(c,'B') returning id into a;
  insert into public.teams(category_id,name) values(c,'C') returning id into t3;
  insert into public.teams(category_id,name) values(c,'D') returning id into t4;
  insert into public.players(team_id,full_name) values(h,'H') returning id into p;
  insert into public.players(team_id,full_name) values(a,'A') returning id into q;
  insert into public.player_initial_goals(player_id,team_id,goals,source) values(p,h,2,'test');
  perform public.close_regular(c);
  perform public.create_semifinals(c,h,a,t3,t4);
  select id into mid from public.matches where category_id=c and home_team_id=h;
  perform public.set_match_player(mid,p,5,true,(select updated_at from public.matches where id=mid));
  perform public.set_match_player(mid,q,6,true,(select updated_at from public.matches where id=mid));
  perform public.save_match_precheck(mid,true,false,true,true,(select updated_at from public.matches where id=mid));
  perform public.control_match(mid,'START',(select updated_at from public.matches where id=mid));
  perform public.record_match_event(mid,h,'GOAL',p,gen_random_uuid());
  perform public.record_match_event(mid,a,'GOAL',q,gen_random_uuid());
  perform public.record_match_event(mid,h,'YELLOW_CARD',p,gen_random_uuid());
  perform public.record_match_event(mid,h,'FOUL',null,gen_random_uuid());
  perform public.control_match(mid,'BREAK',(select updated_at from public.matches where id=mid));
  perform public.control_match(mid,'SECOND_HALF',(select updated_at from public.matches where id=mid));
  perform public.control_match(mid,'PAUSE',(select updated_at from public.matches where id=mid));
  update public.matches set phase_elapsed_seconds=900 where id=mid;
  perform public.open_penalty_shootout(mid,gen_random_uuid(),(select updated_at from public.matches where id=mid));
  perform public.manage_penalty_shootout(mid,'RECORD',h,null,true,gen_random_uuid(),0);
  update public.matchdays set date='2026-10-03';
  before_j:=public.__reset_test_snapshot();
  foreach t in array array['teams','players','matches','match_events','match_players','match_prechecks','match_foul_counters','player_initial_goals','penalty_shootouts','penalty_shootout_attempts','penalty_shootout_operations'] loop
    assert jsonb_array_length(before_j->t)>0,'Fixture must populate '||t;
  end loop;
  set local role anon;
  generation:=public.prepare_tournament_reset();
  rejected:=false;
  begin perform public.reset_tournament('REINICIAR ',generation,rid); exception when raise_exception then rejected:=true; end;
  assert rejected,'Exact confirmation checked by server';
  reset role;
  assert public.__reset_test_snapshot()=before_j;
  create trigger __reset_fail before delete on public.players for each row execute function public.__reset_fail();
  set local role anon;
  rejected:=false;
  begin perform public.reset_tournament('REINICIAR',generation,rid); exception when raise_exception then rejected:=true; end;
  assert rejected;
  reset role;
  assert public.__reset_test_snapshot()=before_j,'Late failure rolls back ALL data including deleted matches and penalties';
  assert (select s.generation from private.tournament_reset_state s)=generation,'Failed reset does not advance generation';
  drop trigger __reset_fail on public.players;
  set local role anon;
  j:=public.reset_tournament('REINICIAR',generation,rid);
  assert j->>'reset'='true';
  reset role;
  foreach t in array array['teams','players','matches','match_events','match_players','match_prechecks','match_foul_counters','player_initial_goals','penalty_shootouts','penalty_shootout_attempts','penalty_shootout_operations'] loop
    execute format('select count(*) from public.%I',t) into n;
    assert n=0,'Reset must empty '||t;
    assert exists(select 1 from pg_class where oid=('public.'||t)::regclass and relrowsecurity),'RLS preserved';
  end loop;
  assert (select count(*) from public.categories)=jsonb_array_length(before_j->'categories');
  assert (select count(*) from public.matchdays)=jsonb_array_length(before_j->'matchdays');
  assert not exists(select 1 from public.categories where regular_closed_at is not null or qualified_team_ids is not null);
  assert not exists(select 1 from public.matchdays where date is not null);
  assert exists(select 1 from pg_trigger where tgname='prevent_goal_delete' and tgenabled='O');
  set local role anon;
  insert into public.teams(category_id,name) values(c,'New tournament team');
  reset role;
  set local role anon;
  j:=public.reset_tournament('REINICIAR',generation,rid);
  assert j->>'replayed'='true','Lost response retry is harmless';
  rejected:=false;
  begin perform public.reset_tournament('REINICIAR',generation,gen_random_uuid()); exception when raise_exception then rejected:=true; end;
  assert rejected,'Stale confirmation cannot reset the new tournament';
  reset role;
  assert (select count(*)=1 from public.teams),'Retry preserves new data';
end $$;
rollback;
