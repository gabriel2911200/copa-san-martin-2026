begin;
do $$ declare c uuid; c2 uuid; h uuid; a uuid; mid uuid; official uuid; p uuid; q uuid; r uuid; j jsonb; before_j jsonb; rid uuid; version timestamptz; rejected boolean; sid uuid;
begin
 insert into public.categories(name) values('__030') returning id into c;
 insert into public.categories(name) values('__030_other') returning id into c2;
 insert into public.teams(category_id,name) values(c,'Santa Rita') returning id into h;
 insert into public.teams(category_id,name) values(c,'Santa Ana') returning id into a;
 insert into public.players(team_id,full_name) values(h,'Juan') returning id into p;
 insert into public.players(team_id,full_name) values(h,'Pedro') returning id into q;
 insert into public.players(team_id,full_name) values(a,'Carlos') returning id into r;
 insert into public.matches(category_id,matchday_id,home_team_id,away_team_id) values(c,(select id from public.matchdays where number=1),h,a) returning id into official;
 set local role anon;
 perform public.manage_duration(1500,false);
 perform public.set_match_duration(official,1500,(select updated_at from public.matches where id=official));
 rid:=gen_random_uuid();
 j:=public.create_friendly(c,h,a,'2026-11-07','18:00',1500,true,rid);mid:=(j->'match'->>'id')::uuid;
 assert mid=rid;
 assert (public.create_friendly(c,h,a,'2026-11-07','18:00',1500,true,rid)->'match')=(j->'match'),'Retry returns the same friendly';
 perform public.manage_duration(1500,true);
 assert not exists(select 1 from public.duration_options where seconds=1500);
 assert (select bool_and(period_duration_seconds=1500) from public.matches where id in(mid,official));
 perform public.set_match_duration(mid,420,(select updated_at from public.matches where id=mid));
 assert not exists(select 1 from public.duration_options where seconds=420),'Custom duration stays outside catalog';
 rejected:=false;
 begin perform public.create_friendly(c,h,h,null,null,900,false,gen_random_uuid()); exception when raise_exception then rejected:=true; end;
 assert rejected,'Self-match rejected';
 perform public.set_match_player(mid,p,8,true,(select updated_at from public.matches where id=mid));
 perform public.set_match_player(mid,q,10,true,(select updated_at from public.matches where id=mid));
 perform public.set_match_player(mid,r,8,true,(select updated_at from public.matches where id=mid));
 version:=(select updated_at from public.matches where id=mid);
 rejected:=false;
 begin perform public.set_match_player(mid,q,8,true,version); exception when raise_exception then rejected:=true; end;
 assert rejected,'Duplicate rejected';
 assert (select shirt_number=10 from public.match_players where match_id=mid and player_id=q),'Previous number kept';
 assert (select updated_at=version from public.matches where id=mid),'Failure did not mutate match';
 perform public.save_match_precheck(mid,true,true,true,true,version);
 perform public.control_match(mid,'START',(select updated_at from public.matches where id=mid));
 before_j:=public.get_tournament();
 perform public.record_match_event(mid,h,'GOAL',p,gen_random_uuid());
 perform public.record_match_event(mid,a,'GOAL',r,gen_random_uuid());
 perform public.record_match_event(mid,h,'YELLOW_CARD',p,gen_random_uuid());
 perform public.set_match_player(mid,p,9,true,(select updated_at from public.matches where id=mid));
 assert (select shirt_number=8 from public.match_events where match_id=mid and player_id=p and type='GOAL'),'Historical event number remains intact';
 assert not exists(select 1 from public.get_top_scorers(c) where player_id=p),'Friendly goals excluded';
 assert (select jsonb_agg(value-'server_now') from jsonb_array_elements(public.get_tournament()->'matches'))=(select jsonb_agg(value-'server_now') from jsonb_array_elements(before_j->'matches')),'Official tournament is unaffected';
 perform public.control_match(mid,'BREAK',(select updated_at from public.matches where id=mid));
 perform public.control_match(mid,'SECOND_HALF',(select updated_at from public.matches where id=mid));
 reset role;
 update public.matches set phase_started_at=clock_timestamp()-interval '430 seconds' where id=mid;
 set local role anon;
 perform public.open_penalty_shootout(mid,gen_random_uuid(),(select updated_at from public.matches where id=mid));
 for i in 0..5 loop
   j:=public.manage_penalty_shootout(mid,'RECORD',case when i%2=0 then h else a end,null,i<>5,gen_random_uuid(),i);
 end loop;
 assert j->'shootout'->>'completed_at' is null,'3-2 is not mathematically decided with five kicks';
 rid:=gen_random_uuid();
 j:=public.manage_penalty_shootout(mid,'FINISH_MANUAL',null,null,null,rid,6);
 assert j->'match'->>'status'='FINALIZADO';
 assert j->'shootout'->'score'='{"home":3,"away":2}'::jsonb;
 assert jsonb_array_length(j->'shootout'->'attempts')=6,'Pending kicks were never recorded';
 assert (j->'shootout'->>'winner_team_id')::uuid=h;
 assert (public.manage_penalty_shootout(mid,'FINISH_MANUAL',null,null,null,rid,6)->'shootout')=(j->'shootout'),'Manual finish is idempotent';
 reset role;
 -- Unauthorized calls cannot reopen; authorized claims are supplied by Auth in production.
 rejected:=false;
 begin perform public.reopen_match(mid,(select updated_at from public.matches where id=mid)); exception when insufficient_privilege then rejected:=true; end;
 assert rejected;
 perform set_config('request.jwt.claims',jsonb_build_object('role','authenticated','sub',gen_random_uuid(),'app_metadata',jsonb_build_object('role','admin'))::text,true);
 j:=public.reopen_match(mid,(select updated_at from public.matches where id=mid));
 assert j->'match'->>'status'='PAUSADO';
 assert (j->'match'->>'phase_elapsed_seconds')::int=420;
 assert jsonb_array_length(j->'shootout'->'attempts')=6;
 assert j->'shootout'->>'completed_at' is null;
 assert (select count(*)=1 from private.match_reopen_audit where match_id=mid);
 set local role anon;
 j:=public.manage_penalty_shootout(mid,'FINISH_MANUAL',null,null,null,gen_random_uuid(),8);
 assert j->'match'->>'status'='FINALIZADO';
 -- Reopen ordinary match, resume without resetting its clock, finish again.
 perform public.save_match_precheck(official,true,true,true,true,(select updated_at from public.matches where id=official));
 perform public.control_match(official,'START',(select updated_at from public.matches where id=official));
 perform public.control_match(official,'BREAK',(select updated_at from public.matches where id=official));
 perform public.control_match(official,'SECOND_HALF',(select updated_at from public.matches where id=official));
 reset role;
 update public.matches set phase_started_at=clock_timestamp()-interval '73 seconds' where id=official;
 set local role anon;
 j:=public.control_match(official,'FINISH',(select updated_at from public.matches where id=official));
 reset role;
 j:=public.reopen_match(official,(select updated_at from public.matches where id=official));
 assert (j->'match'->>'phase_elapsed_seconds')::int>=73;
 set local role anon;
 j:=public.control_match(official,'RESUME',(select updated_at from public.matches where id=official));
 assert (j->'match'->>'phase_elapsed_seconds')::int>=73;
 perform public.control_match(official,'FINISH',(select updated_at from public.matches where id=official));
 reset role;
end $$;
rollback;
